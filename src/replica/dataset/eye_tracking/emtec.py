"""EMTeC: Eye Movements on Machine-generated Texts Corpus (Bolliger et al., 2025).

Eye-tracking data for texts generated by different LLMs under various decoding
strategies, read by native English speakers.

Data format expected:
- ``reading_measures.csv``: despite the .csv extension, this file is
  tab-separated (TSV). Columns include:
  [subject_id, item_id, model, decoding_strategy, type, task,
   word_id, word, FFD, FPRT, TFT, RPD_inc, ...]

Each unique (item_id, model, decoding_strategy) combination is a distinct Stimulus.

Data notes:
    Some (model, decoding_strategy) cells are absent from the raw data, so
    the stimulus count sits below the full factorial; the shipped counts
    snapshot records what the loader builds. The experiment uses a
    between-subjects design, so each stimulus is read by a small subset of
    the participants.

Reference: https://doi.org/10.3758/s13428-025-02677-4
"""

import csv
from pathlib import Path

from replica.dataset.base import EyeTrackingDataset
from replica.dataset.contracts import DatasetInfo, Fixation
from replica.dataset.measures import PYMOVEMENTS_MEASURE_NAMES, pymovements_measures
from replica.dataset.metadata import io as metadata_io

from ...core import Datum, Stimulus
from ..loading.fixation_utils import (
    RunIdInferrer,
    SyntheticTimer,
    append_fixation,
    replace_with_fixation_measures,
)
from ..loading.utils import (
    append_measure_datums,
    parse_float,
    parse_reading_measure,
    scatter_measure_tuples,
)


class EMTeC(EyeTrackingDataset):
    """EMTeC eye-tracking corpus (Bolliger et al., 2025).

    Eye-tracking data for machine-generated texts from 3 models
    (Mistral, Phi-2, WizardLM) under 5 decoding strategies, read
    by native English speakers.
    """

    info = DatasetInfo(name="emtec", language="en")
    _declared_measures = (*PYMOVEMENTS_MEASURE_NAMES, "go_past")

    def __init__(self, measurement_source: str = "fixations"):
        """Select complete fixation measures or the original released summaries.

        Args:
            measurement_source: ``"fixations"`` for the author's fixed exporter
                calculation, which includes all terminal events and keeps the
                author's integer-millisecond conversion and exclusion of
                off-word events (the event API keeps the original durations);
                ``"released"`` for the original summary tables, which omit
                each trial's final word-aligned fixation.
        """
        super().__init__()
        if measurement_source not in {"fixations", "released"}:
            raise ValueError("measurement_source must be 'fixations' or 'released'")
        self.measurement_source = measurement_source

    def load(
        self,
        path: str,
        data_file: str = "reading_measures.csv",
    ) -> None:
        """Load EMTeC data from disk.

        Args:
            path: Directory containing the data files.
            data_file: Reading measures CSV file name (per-word; required).

        ``fixations.csv`` is required for the default complete measurements.
        It is optional when ``measurement_source="released"``.
        """
        used_files = [data_file]
        if (Path(path) / "fixations.csv").exists():
            used_files.append("fixations.csv")
        self._load_metadata(
            path,
            files=used_files,
            metadata_path=metadata_io.find_dataset_yaml(
                "eye-tracking/original/emtec", required=True
            ),
        )
        # Keep this English-only loader's language explicit after loading metadata.
        self.info.language = "en"
        base = Path(path)
        self._load_data(base / data_file)
        self._add_arrival_go_past()

        self._fixations: list[Fixation] = []
        fix_file = base / "fixations.csv"
        if fix_file.exists():
            self._load_fixations(fix_file)
        elif self.measurement_source == "fixations":
            raise FileNotFoundError(
                "EMTeC complete measures require fixations.csv; run `replica fetch emtec`"
            )
        if self.measurement_source == "fixations":
            replace_with_fixation_measures(
                self._data,
                self._fixations,
                floor_durations=True,
                off_text_ends_run=False,
            )

    def _load_data(self, data_path: Path) -> None:
        """Parse reading measures CSV into Stimulus and Datum objects."""
        # stim_key = (item_id, model, decoding_strategy)
        # stim_key → sorted list of (word_id, word_str) for building stimuli
        stim_words: dict[tuple[str, str, str], list[tuple[int, str]]] = {}
        # stim_key → metadata (type, task) from first row seen
        stim_meta: dict[tuple[str, str, str], dict[str, str]] = {}

        # stim_key → subject_id → {word_id: {measure: value}}
        obs: dict[
            tuple[str, str, str],
            dict[str, dict[int, tuple[float, ...]]],
        ] = {}

        with open(data_path, encoding="utf-8") as f:
            reader = csv.DictReader(f, delimiter="\t")
            for row in reader:
                item_id = row["item_id"].strip()
                model = row["model"].strip()
                dec_strat = row["decoding_strategy"].strip()
                subject = row["subject_id"].strip()
                word_id = int(row["word_id"])
                word = row["word"]

                stim_key = (item_id, model, dec_strat)

                # Collect words for stimulus (deduplicate)
                word_list = stim_words.setdefault(stim_key, [])
                existing_ids = {wid for wid, _ in word_list}
                if word_id not in existing_ids:
                    word_list.append((word_id, word))

                elif dict(word_list)[word_id] != word:
                    raise ValueError(
                        f"Conflicting EMTeC word label for {stim_key}, word {word_id}"
                    )

                # Store stimulus metadata from first row
                if stim_key not in stim_meta:
                    stim_meta[stim_key] = {
                        "item_id": item_id,
                        "model": model,
                        "decoding_strategy": dec_strat,
                        "type": row.get("type", "").strip(),
                        "task": row.get("task", "").strip(),
                    }

                # Collect measures
                subj_data = obs.setdefault(stim_key, {})
                word_data = subj_data.setdefault(subject, {})

                # Collect measures as a fixed-order tuple to avoid per-row
                # dict overhead (EMTeC has hundreds of thousands of rows).
                # FD reports first arrival; FFD/FPRT report first-pass windows.
                # Released FRT is incomplete; FPRT supplies the known first-pass runs.
                if word_id in word_data:
                    raise ValueError(
                        f"Duplicate EMTeC summary row for {subject}, {stim_key}, word {word_id}"
                    )
                word_data[word_id] = pymovements_measures(
                    row.__getitem__,
                    unfixated=parse_reading_measure(row.get("TFT", "")) == 0.0,
                )

        # Build Stimulus objects
        stim_map: dict[tuple[str, str, str], Stimulus] = {}
        self._stimuli: list[Stimulus] = []

        for stim_key in sorted(stim_words.keys()):
            word_list = sorted(stim_words[stim_key], key=lambda x: x[0])
            words = [w for _, w in word_list]

            item_id, model, dec_strat = stim_key
            stimulus = self._make_stimulus(
                words,
                f"emtec_{item_id}_{model}_{dec_strat}",
                stim_meta[stim_key],
            )
            stim_map[stim_key] = stimulus

        # Build Datum objects: one per (participant, stimulus, measure)
        self._data: list[Datum] = []
        for stim_key, subj_dict in obs.items():
            stimulus = stim_map[stim_key]
            n_words = len(stimulus.layers["words"])

            # Build a mapping from word_id to array index
            word_list = sorted(stim_words[stim_key], key=lambda x: x[0])
            word_id_to_idx = {wid: idx for idx, (wid, _) in enumerate(word_list)}

            measure_names = PYMOVEMENTS_MEASURE_NAMES
            for subject, word_measures in subj_dict.items():
                # Scatter the sparse per-word measure tuples into dense
                # arrays; tuple order follows PYMOVEMENTS_MEASURE_NAMES
                # (locked at parse time).
                values_per_measure = scatter_measure_tuples(
                    word_measures.items(),
                    word_id_to_idx,
                    n_words,
                    len(measure_names),
                )

                append_measure_datums(
                    self._data,
                    stimulus=stimulus,
                    participant_id=subject,
                    measure_names=measure_names,
                    measure_values=values_per_measure,
                    metadata={"measurement_source": "released"},
                )

        # Stash word_id-to-index maps for fixation parsing. The
        # words layer is built from reading_measures.csv; fixation rows
        # use the same word_id convention.
        for stim_key, stimulus in stim_map.items():
            wl = sorted(stim_words[stim_key], key=lambda x: x[0])
            stimulus.metadata["word_id_to_idx"] = {
                wid: idx for idx, (wid, _) in enumerate(wl)
            }
        self._stim_lookup = stim_map  # used by _load_fixations

    # Fixation-level loading from ``fixations.csv`` (tab-separated).
    # No per-fix start/end timestamps and no EyeLink IA dwell column;
    # trial-relative ``start_time`` is synthesized from cumulative durations
    # per (subject, trial) (``metadata['synthetic_start_time'] = True``).
    #
    # Columns:
    #   subject_id, item_id, model, decoding_strategy   identifying tuple
    #   TRIAL_ID                                         trial within session
    #   fixation_index                                   1-based ordinal in trial
    #   fixation_duration                                ms
    #   fix_mean_x, fix_mean_y                           pixel coords
    #   word_id, word                                    IA the fixation landed on
    def _load_fixations(self, fix_file: Path) -> None:
        # Per-(subject, trial) helpers for synthesizing start times and
        # inferring EyeLink-style run_id.
        timer = SyntheticTimer()
        run_ids = RunIdInferrer()

        with open(fix_file, encoding="utf-8") as f:
            reader = csv.DictReader(f, delimiter="\t")
            for row in reader:
                item_id = row["item_id"].strip()
                model = row["model"].strip()
                dec_strat = row["decoding_strategy"].strip()
                stim_key = (item_id, model, dec_strat)
                stim = self._stim_lookup.get(stim_key)
                if stim is None:
                    raise ValueError(f"Unknown EMTeC fixation stimulus: {stim_key}")

                subject = row["subject_id"].strip()
                try:
                    trial = int(row["TRIAL_ID"])
                    fix_idx = int(row["fixation_index"])
                    dur = float(row["fixation_duration"])
                except (KeyError, ValueError) as error:
                    raise ValueError(
                        f"Invalid EMTeC fixation at row {reader.line_num}"
                    ) from error

                # The release marks off-text fixations with a literal dot.
                # Keep their duration in the timeline without assigning it to a word.
                raw_word_id = row["word_id"].strip()
                unit_index = None
                char_offset = None
                if raw_word_id != ".":
                    word_id = int(raw_word_id)
                    wid_to_idx = stim.metadata["word_id_to_idx"]
                    if word_id not in wid_to_idx:
                        raise ValueError(
                            f"EMTeC fixation word_id {word_id} is absent from {stim_key}"
                        )
                    unit_index = wid_to_idx[word_id]
                    char_offset = stim.layers["words"].spans[unit_index].start

                # Pixel coordinates, pass through, NaN if unparseable.
                x = parse_float(row.get("fix_mean_x", ""))
                y = parse_float(row.get("fix_mean_y", ""))

                trial_key = (subject, trial)
                start, end = timer.next(trial_key, dur)

                meta = {
                    "trial_index": trial,
                    "synthetic_start_time": True,
                }
                # The author's measure calculator skips off-word events before
                # determining runs. Preserve that convention in source run IDs.
                run_id = (
                    run_ids.next(trial_key, unit_index)
                    if unit_index is not None
                    else None
                )
                if run_id is not None:
                    meta["run_id"] = run_id
                append_fixation(
                    self._fixations,
                    participant_id=subject,
                    stimulus_id=stim.stimulus_id,
                    start_time=start,
                    end_time=end,
                    duration=dur,
                    x=x,
                    y=y,
                    unit_index=unit_index,
                    char_offset=char_offset,
                    fixation_index=fix_idx,
                    metadata=meta,
                )

    # ``fixations()`` inherits from EyeTrackingDataset.
    # ``unit_index`` is aligned to the stimulus's ``"words"`` layer (built
    # from ``reading_measures.csv``). EMTeC's ``fixations.csv`` doesn't
    # ship per-fixation timestamps; ``start_time`` is synthesized via
    # :class:`SyntheticTimer` (``metadata["synthetic_start_time"] = True``).
